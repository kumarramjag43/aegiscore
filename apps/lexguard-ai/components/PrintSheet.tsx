"use client";

import { BAND_LABEL, formatMoney, type AuditReport } from "@aegiscore/core";

/**
 * Print-only rendition of the executive audit. Hidden on screen; when the user
 * prints or saves as PDF, this replaces the console so the artefact is a clean,
 * signature-ready document rather than a screenshot of a dashboard.
 */
export function PrintSheet({ report, title }: { report: AuditReport; title: string }) {
  const exposure = report.risk.exposure;
  const when = new Date(report.createdAt);

  return (
    <div className="hidden bg-white text-[#121826] print:block">
      <header className="border-b-2 border-[#121826] pb-3">
        <p className="font-serif text-[10px] uppercase tracking-[0.28em] text-[#7a5c1e]">
          AegisCore · LexGuard AI · Executive audit
        </p>
        <h1 className="mt-1 font-serif text-2xl font-semibold">{title || report.input.title}</h1>
        <p className="mt-1 text-[11px] text-[#3d4659]">
          Report {report.id} · {when.toLocaleString("en-US")} · {report.domainLabel} ·{" "}
          {report.provider.mode === "live" ? `live model (${report.provider.label})` : "deterministic sandbox engine"}
        </p>
      </header>

      <section className="mt-4 grid grid-cols-4 gap-3 text-[11px]">
        <Metric label="Risk score" value={`${report.risk.score}/100`} note={BAND_LABEL[report.risk.band]} />
        <Metric label="Red-flag clauses" value={String(report.findings.length)} note={`${report.patches.length} redlines`} />
        <Metric
          label="Financial exposure"
          value={
            exposure
              ? `${formatMoney(exposure.low, exposure.currency)} – ${formatMoney(exposure.high, exposure.currency)}`
              : "not quantified"
          }
          note={exposure ? exposure.basis : "no monetary commitment found"}
        />
        <Metric
          label="Verification"
          value={report.verification.passed ? "PASSED" : "FAILED"}
          note={`${report.verification.confidence}% confidence · ${report.verification.checks.filter((c) => c.passed).length}/${report.verification.checks.length} checks`}
        />
      </section>

      <section className="mt-5">
        <h2 className="font-serif text-sm font-semibold uppercase tracking-[0.14em]">1. Findings</h2>
        <table className="mt-2 w-full border-collapse text-[10.5px]">
          <thead>
            <tr className="border-b border-[#121826]/25 text-left">
              <th className="py-1 pr-2 font-semibold">ID</th>
              <th className="py-1 pr-2 font-semibold">Severity</th>
              <th className="py-1 pr-2 font-semibold">Score</th>
              <th className="py-1 pr-2 font-semibold">Location</th>
              <th className="py-1 pr-2 font-semibold">Finding</th>
              <th className="py-1 font-semibold">Counter-position</th>
            </tr>
          </thead>
          <tbody>
            {report.findings.map((finding) => (
              <tr key={finding.id} className="border-b border-[#121826]/10 align-top">
                <td className="py-1 pr-2 font-mono">{finding.id}</td>
                <td className="py-1 pr-2 font-semibold uppercase">{finding.severity}</td>
                <td className="py-1 pr-2 font-mono">{finding.score}</td>
                <td className="py-1 pr-2">{finding.location}</td>
                <td className="py-1 pr-2">{finding.title}</td>
                <td className="py-1">{finding.recommendation}</td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>

      <section className="mt-5 break-before-page">
        <h2 className="font-serif text-sm font-semibold uppercase tracking-[0.14em]">
          2. Counter-proposal &amp; audit notice
        </h2>
        <pre className="mt-2 whitespace-pre-wrap font-serif text-[10.5px] leading-relaxed text-[#1b2233]">
          {report.repairedDocument}
        </pre>
      </section>

      <section className="mt-5">
        <h2 className="font-serif text-sm font-semibold uppercase tracking-[0.14em]">3. Verification record</h2>
        <ul className="mt-2 text-[10.5px]">
          {report.verification.checks.map((check) => (
            <li key={check.id} className="flex gap-2 border-b border-[#121826]/10 py-1">
              <span className="font-mono">{check.passed ? "PASS" : "FAIL"}</span>
              <span className="font-semibold">{check.label}</span>
              <span className="text-[#3d4659]">{check.detail}</span>
            </li>
          ))}
        </ul>
      </section>

      <footer className="mt-6 border-t border-[#121826]/25 pt-2 text-[9.5px] text-[#3d4659]">
        Generated by AegisCore ({report.id}) — one multi-agent skeleton powering CodeMedic AI and LexGuard AI.
        Automated analysis is decision support, not legal advice; obtain professional review before signature.
      </footer>
    </div>
  );
}

function Metric({ label, value, note }: { label: string; value: string; note: string }) {
  return (
    <div className="border border-[#121826]/20 p-2">
      <p className="text-[9px] uppercase tracking-wider text-[#5a6479]">{label}</p>
      <p className="mt-0.5 font-semibold">{value}</p>
      <p className="mt-0.5 text-[9px] leading-snug text-[#5a6479]">{note}</p>
    </div>
  );
}
