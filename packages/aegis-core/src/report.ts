import { escapeFence } from "./json";
import type { AuditReport, DomainPack } from "./types";

export function formatMoney(amount: number, currency = "USD"): string {
  try {
    return new Intl.NumberFormat("en-US", {
      style: "currency",
      currency,
      maximumFractionDigits: 0,
    }).format(amount);
  } catch {
    return `${currency} ${Math.round(amount).toLocaleString("en-US")}`;
  }
}

const SEVERITY_LABEL: Record<string, string> = {
  critical: "Critical",
  high: "High",
  medium: "Medium",
  low: "Low",
  info: "Info",
};

/**
 * The exportable markdown artefact. It is deliberately self-contained: a judge
 * (or a customer) can download it and hand it to an engineer or a lawyer with
 * no additional context.
 */
export function buildMarkdown(args: {
  report: Omit<AuditReport, "markdown">;
  pack: DomainPack;
  unified: string;
}): string {
  const { report, pack, unified } = args;
  const { risk, findings, patches, verification } = report;
  const lines: string[] = [];

  lines.push(`# AegisCore Audit — ${report.input.title}`);
  lines.push("");
  lines.push(
    `> Generated by **AegisCore** (${pack.label}) · run \`${report.id}\` · ${report.createdAt}`,
  );
  lines.push(`> Provider: **${report.provider.label}** (${report.provider.mode})`);
  lines.push("");

  lines.push("## 1. Executive summary");
  lines.push("");
  lines.push(`**Risk score:** ${risk.score}/100 · **Band:** ${risk.band.toUpperCase()} · **Severity:** ${SEVERITY_LABEL[risk.severity]}`);
  lines.push("");
  lines.push(risk.verdict);
  lines.push("");
  if (risk.exposure) {
    lines.push(
      `**Financial exposure:** ${formatMoney(risk.exposure.low, risk.exposure.currency)} – ${formatMoney(
        risk.exposure.high,
        risk.exposure.currency,
      )} _(${risk.exposure.basis})_`,
    );
    lines.push("");
  }
  lines.push("| Metric | Value |");
  lines.push("| --- | --- |");
  lines.push(`| ${pack.documentNoun} length | ${report.input.characters.toLocaleString()} characters |`);
  lines.push(`| Structured chunks | ${report.input.chunks} |`);
  lines.push(`| Findings | ${findings.length} |`);
  lines.push(`| Patches applied | ${patches.length} |`);
  lines.push(`| Verification | ${verification.passed ? "PASSED" : "ATTENTION REQUIRED"} (${verification.confidence}% confidence) |`);
  lines.push(`| Critic score (advisory) | ${risk.criticScore} |`);
  lines.push(`| Core score (authoritative) | ${risk.score} |`);
  lines.push("");

  lines.push("## 2. Findings");
  lines.push("");
  if (findings.length === 0) {
    lines.push("No material findings were identified in this artefact.");
    lines.push("");
  }
  findings.forEach((finding, index) => {
    const fence = escapeFence(finding.evidence);
    lines.push(
      `### ${index + 1}. ${finding.title} — ${SEVERITY_LABEL[finding.severity]} (${finding.score}/100)`,
    );
    lines.push("");
    lines.push(`- **ID:** \`${finding.id}\``);
    lines.push(`- **Location:** ${finding.location}`);
    lines.push(`- **Category:** ${finding.category}`);
    lines.push("");
    lines.push("**Evidence**");
    lines.push("");
    lines.push(`${fence}text`);
    lines.push(finding.evidence);
    lines.push(fence);
    lines.push("");
    lines.push(`**Why it matters.** ${finding.explanation}`);
    lines.push("");
    lines.push(`**Recommendation.** ${finding.recommendation}`);
    lines.push("");
  });

  lines.push("## 3. Remediation");
  lines.push("");
  lines.push(`**Strategy.** ${report.healStrategy}`);
  lines.push("");
  patches.forEach((patch, index) => {
    const beforeFence = escapeFence(patch.original);
    const afterFence = escapeFence(patch.replacement);
    lines.push(`### Patch ${index + 1}. ${patch.title}`);
    lines.push("");
    lines.push(`_${patch.rationale}_`);
    lines.push("");
    lines.push("**Before**");
    lines.push("");
    lines.push(`${beforeFence}text`);
    lines.push(patch.original);
    lines.push(beforeFence);
    lines.push("");
    lines.push("**After**");
    lines.push("");
    lines.push(`${afterFence}text`);
    lines.push(patch.replacement);
    lines.push(afterFence);
    lines.push("");
  });

  if (unified) {
    lines.push("### Unified diff");
    lines.push("");
    lines.push("```diff");
    lines.push(unified);
    lines.push("```");
    lines.push("");
  }

  lines.push("## 4. Verification");
  lines.push("");
  lines.push("| Check | Result | Detail |");
  lines.push("| --- | --- | --- |");
  for (const check of verification.checks) {
    lines.push(`| ${check.label} | ${check.passed ? "PASS" : "FAIL"} | ${check.detail.replace(/\|/g, "\\|")} |`);
  }
  lines.push("");
  for (const note of verification.notes) lines.push(`- ${note}`);
  lines.push("");

  lines.push(`## 5. Remediated ${pack.documentNoun}`);
  lines.push("");
  const docFence = escapeFence(report.repairedDocument);
  lines.push(`${docFence}text`);
  lines.push(report.repairedDocument);
  lines.push(docFence);
  lines.push("");

  lines.push("## 6. Run metadata");
  lines.push("");
  lines.push("| Agent | Duration |");
  lines.push("| --- | --- |");
  for (const timing of report.timings) {
    lines.push(`| ${pack.agents[timing.stage].name} | ${timing.ms} ms |`);
  }
  lines.push(`| **Total** | **${report.totalMs} ms** |`);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push(
    "Generated by AegisCore — one modular multi-agent core, two domain packs. " +
      "This report is automated analysis, not professional legal or security advice.",
  );
  lines.push("");

  return lines.join("\n");
}
