const RACE_CONDITION = [
  "// services/ledger.js — wallet withdrawals and token issuing",
  'import { createHash, randomUUID } from "node:crypto";',
  'import { db } from "../db.js";',
  "",
  "export async function withdraw(accountId, amount) {",
  "  const account = await db.accounts.findOne({ _id: accountId });",
  '  if (!account) throw new Error("account not found");',
  '  if (account.balance < amount) throw new Error("insufficient funds");',
  "",
  "  account.balance -= amount;",
  "  await db.accounts.updateOne({ _id: accountId }, { balance: account.balance });",
  "  return account.balance;",
  "}",
  "",
  "export function fingerprint(payload) {",
  '  return createHash("md5").update(JSON.stringify(payload)).digest("hex");',
  "}",
  "",
  "export function issueSessionToken() {",
  "  return Math.random().toString(36).slice(2);",
  "}",
  "",
  "export async function listAuditTrail(limit = 25) {",
  "  const cursor = db.audit.find({}).sort({ at: -1 }).limit(limit);",
  "  return cursor.toArray();",
  "}",
  "",
  "void randomUUID;",
].join("\n");

